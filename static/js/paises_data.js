function normalizeCountryName(rawName) {
    if (!rawName) return '';
    let name = String(rawName).trim();
    if (!name || name === 'Não Informado' || name === 'Não informado' || name === '-') return '';
    if (COUNTRY_FLAG_MAP[name]) return name;

    const lower = name.toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '');
    if (COUNTRY_NAME_ALIASES[lower]) return COUNTRY_NAME_ALIASES[lower];

    for (const officialName of Object.keys(COUNTRY_FLAG_MAP)) {
        const offLower = officialName.toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '');
        if (offLower === lower) return officialName;
    }
    return name;
}

function getCountryFlagInfo(countryName) {
    const normalized = normalizeCountryName(countryName);
    if (!normalized) return null;
    const entry = COUNTRY_FLAG_MAP[normalized];
    if (entry) {
        return { name: normalized, code: entry.code, emoji: entry.emoji };
    }
    return { name: normalized, code: 'un', emoji: '🌐' };
}

function getCountryFlagImgHtml(infoOrName, extraClass = '') {
    if (!infoOrName) return '<i class="bi bi-globe me-1 text-muted"></i>';
    const info = (typeof infoOrName === 'string') ? getCountryFlagInfo(infoOrName) : infoOrName;
    if (!info) return '<i class="bi bi-globe me-1 text-muted"></i>';

    if (info.code === 'un' || !info.code) {
        return '<span class="country-flag-icon ' + extraClass + '" title="' + info.name + '">🌐</span>';
    }

    return (
        '<span class="d-inline-flex align-items-center country-flag-wrapper ' + extraClass + '">' +
            '<img src="https://flagcdn.com/20x15/' + info.code + '.png" ' +
                 'srcset="https://flagcdn.com/40x30/' + info.code + '.png 2x" ' +
                 'width="16" height="12" ' +
                 'alt="' + info.name + '" ' +
                 'class="rounded-1 shadow-xs country-flag-img" ' +
                 'style="object-fit: cover; border: 1px solid rgba(0,0,0,0.15); display: inline-block; vertical-align: middle;" ' +
                 'loading="lazy" ' +
                 'onerror="this.style.display=\'none\'; if(this.nextElementSibling) this.nextElementSibling.style.display=\'inline\';">' +
            '<span class="country-flag-fallback" style="display: none; font-size: 13px;">' + (info.emoji || '🌐') + '</span>' +
        '</span>'
    );
}

function getCountryBadgeHtml(countryName, isSmall = false) {
    if (!countryName || countryName === 'Não Informado' || countryName === 'Não informado' || countryName === '-') return '';
    const info = getCountryFlagInfo(countryName);
    if (!info) return '';
    const flagHtml = getCountryFlagImgHtml(info);
    const sizeStyle = isSmall ? 'font-size: 0.70rem; padding: 2px 6px;' : 'font-size: 0.72rem; padding: 2px 7px;';
    return (
        '<span class="badge bg-light text-dark border d-inline-flex align-items-center gap-1 shadow-sm country-flag-badge" ' +
              'style="' + sizeStyle + ' vertical-align: middle;" title="País de publicação / origem: ' + info.name + '">' +
            flagHtml +
            '<span>' + info.name + '</span>' +
        '</span>'
    );
}

